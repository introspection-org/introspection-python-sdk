#!/usr/bin/env python3
"""Generate the sync SDK in ``introspection_sdk/_sync/`` from ``_async/``.

Every class or function with an ``Async*`` twin is written once, as async
code under ``introspection_sdk/_async/``, and this script derives the sync
twin from it with `unasync <https://github.com/python-trio/unasync>`_, the
way httpx/httpcore and urllib3 do. The public modules
(``introspection_sdk/runner_resources/tasks.py`` and so on) re-export both
twins, so no import path changes.

unasync rewrites tokens: it drops ``async`` and ``await`` and renames each
name token found in ``TOKENS``. A name with no entry there follows the
``Async*`` / ``async_*`` / ``*_async`` rules in ``_unasync_name``. Text it
cannot reach as one token (a dotted call, a phrase inside a docstring) goes
goes through the regular expressions in ``SUBSTITUTIONS``, in order. The
output is then import-sorted and formatted with the repository's ruff
config.

Code that genuinely differs between sync and async stays hand-written next
to its public module and is not listed here; see "Sync code generation" in
AGENTS.md.

Run after editing anything under ``introspection_sdk/_async/``:

    uv run python scripts/unasync.py

``--check`` regenerates in memory and fails on any difference from the
committed ``_sync/`` tree; CI runs it.
"""

from __future__ import annotations

import argparse
import difflib
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

# This script shares its name with the library it drives: drop its own
# directory from the import path so that import unasync finds the
# library and not this file.
sys.path[:] = [
    p
    for p in sys.path
    if Path(p or ".").resolve() != Path(__file__).resolve().parent
]

import unasync  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "introspection_sdk" / "_async"
TARGET = ROOT / "introspection_sdk" / "_sync"

HEADER = (
    "# Generated by scripts/unasync.py from {source}. Do not edit:\n"
    "# change the async source and run `uv run python scripts/unasync.py`.\n"
)

# Name tokens unasync renames, on top of its own defaults (__aenter__,
# __aexit__, __aiter__, __anext__, asynccontextmanager, AsyncIterable,
# AsyncIterator, AsyncGenerator, StopAsyncIteration). A string literal is
# renamed only when its whole content is one of these names.
TOKENS = {
    # The source and generated packages.
    "_async": "_sync",
    # httpx / httpx2.
    "AsyncClient": "Client",
    "AsyncBaseTransport": "BaseTransport",
    "AsyncHTTPTransport": "HTTPTransport",
    "AsyncByteStream": "SyncByteStream",
    "aclose": "close",
    "aiter_bytes": "iter_bytes",
    "aiter_lines": "iter_lines",
    "aiter_raw": "iter_raw",
    "aread": "read",
    "handle_async_request": "handle_request",
    # Hand-written helpers whose sync name is not a prefix strip.
    "_acp_post": "_cp_post",
    "_apost_token_form": "_post_token_form",
}

# Regular expressions applied in order to each generated file, after the
# token pass: what unasync cannot see as one token. Dotted calls and
# imports, a type that only exists to be awaited, and docstring prose. The
# loops and comprehensions that are only spelled out because they are
# ``async`` are rewritten by ruff's UP028 and C416 fixes in ``_finish``.
SUBSTITUTIONS: list[tuple[str, str]] = [
    # A block the sync twin does not have, such as ``__aenter__`` on a
    # client whose sync twin is no context manager, is fenced in the source
    # by these two comments and left out of the generated file. The first
    # one may carry the reason after the marker.
    (
        r"^[ \t]*# unasync: async-only\b.*\n(?s:.*?)^[ \t]*# unasync: end\n\n?",
        "",
    ),
    (r"^import asyncio$", "import time"),
    (r"\basyncio\.sleep\(", "time.sleep("),
    (r"\bAwaitable\[((?:[^\[\]]|\[[^\[\]]*\])*)\]", r"\1"),
    (r"\bAsync twins re-exported by\b", "Sync twins re-exported by"),
    # A cross-reference in prose, like :class:`AsyncPager`.
    (r"\bAsync([A-Z]\w*)", r"\1"),
    (r"\bAsynchronous\b", "Synchronous"),
    (r"\basynchronous\b", "synchronous"),
]


class _Rule(unasync.Rule):
    def _unasync_name(self, name: str) -> str:
        if name in self.token_replacements:
            return self.token_replacements[name]
        # AsyncTasks -> Tasks, _AsyncHttpClient -> _HttpClient.
        for prefix in ("Async", "_Async"):
            rest = name[len(prefix) :]
            if name.startswith(prefix) and rest[:1].isupper():
                return prefix[: -len("Async")] + rest
        # async_cursor_paginate -> cursor_paginate,
        # parse_ag_ui_events_async -> parse_ag_ui_events.
        if name.startswith("async_"):
            return name[len("async_") :]
        if name.endswith("_async"):
            return name[: -len("_async")]
        return name


def _ruff(args: list[str], source: str, filename: Path) -> str:
    result = subprocess.run(
        [
            sys.executable,
            "-m",
            "ruff",
            *args,
            "--stdin-filename",
            str(filename),
            "-",
        ],
        input=source,
        capture_output=True,
        text=True,
        check=False,
        cwd=ROOT,
    )
    if result.returncode != 0:
        sys.exit(
            f"ruff {' '.join(args)} failed on {filename}:\n{result.stderr}"
        )
    return result.stdout


def _finish(raw: str, source: Path, target: Path) -> str:
    for pattern, replacement in SUBSTITUTIONS:
        raw = re.sub(pattern, replacement, raw, flags=re.MULTILINE)
    raw = HEADER.format(source=source.relative_to(ROOT).as_posix()) + raw
    # Imports only the async code used (asyncio, Awaitable) go unused, and
    # the async spelling of a loop (UP028) or a list() (C416) is rewritten.
    # UP028's fix is unsafe only for generators driven with send()/throw(),
    # which none of these are.
    raw = _ruff(
        [
            "check",
            "--fix",
            "--unsafe-fixes",
            "--select",
            "I,F401,UP028,C416",
            "--quiet",
        ],
        raw,
        target,
    )
    return _ruff(["format", "--quiet"], raw, target)


def generate() -> dict[Path, str]:
    """Return every generated file's path and contents, writing nothing."""
    out: dict[Path, str] = {}
    with tempfile.TemporaryDirectory() as tmp:
        work = Path(tmp) / "_async"
        shutil.copytree(
            SOURCE, work, ignore=shutil.ignore_patterns("__pycache__")
        )
        sources = sorted(work.rglob("*.py"))
        unasync.unasync_files(
            [str(p) for p in sources],
            [_Rule("/_async/", "/_sync/", TOKENS)],
        )
        for src in sources:
            rel = src.relative_to(work)
            raw = (Path(tmp) / "_sync" / rel).read_text()
            out[TARGET / rel] = _finish(raw, SOURCE / rel, TARGET / rel)
    return out


def _committed() -> dict[Path, str]:
    return {
        p: p.read_text()
        for p in TARGET.rglob("*.py")
        if "__pycache__" not in p.parts
    }


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Generate introspection_sdk/_sync/ from _async/."
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail if introspection_sdk/_sync/ is not up to date",
    )
    args = parser.parse_args()

    expected = generate()
    committed = _committed()
    if args.check:
        stale = False
        for path in sorted(expected.keys() | committed.keys()):
            want, have = expected.get(path, ""), committed.get(path, "")
            if want != have:
                stale = True
                name = path.relative_to(ROOT).as_posix()
                sys.stdout.writelines(
                    difflib.unified_diff(
                        have.splitlines(keepends=True),
                        want.splitlines(keepends=True),
                        f"a/{name}",
                        f"b/{name}",
                    )
                )
        if stale:
            print(
                "\nintrospection_sdk/_sync/ is out of date: run "
                "`uv run python scripts/unasync.py` and commit the result.",
                file=sys.stderr,
            )
            return 1
        return 0

    for path in committed.keys() - expected.keys():
        path.unlink()
    for path, text in expected.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        if committed.get(path) != text:
            path.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
